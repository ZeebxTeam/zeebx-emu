#!/usr/bin/env python3
"""Installs the Libretro core into RetroArch: the `.so` **and** the `.info`, always together.

The two go as a pair: RetroArch reads the `.info`'s `database` field to associate the No-Intro
database with the core, and an old `.info` next to a new core makes the scan from the interface mark
`??` on everything. That is exactly what happened here once, from installing the two at different
moments.

    python3 tools/install_core.py                 # copies into the user's RetroArch
    python3 tools/install_core.py --dest DIR      # another cores folder
    python3 tools/install_core.py --release       # uses target/release

And for the **muOS card**, which is laid out differently (the launcher calls
`retroarch -L /opt/muos/share/core/<core>`, and the system needs the associations in
`info/assign`):

    python3 tools/install_core.py --muos /media/$USER/ROOTFS
    python3 tools/install_core.py --muos /media/$USER/ROOTFS --soundfont Bank.sf2
    python3 tools/install_core.py --muos /media/$USER/ROOTFS \
      --so zeebx_libretro.so --info zeebx_libretro.info --soundfont GeneralUser-GS.sf2

The Portuguese option names (`--destino`, `--banco`) are still accepted.
"""

import argparse
import pathlib
import shutil
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCE_INFO = ROOT / "frontends" / "libretro" / "zeebx_libretro.info"
NAMES = ("libzeebx_libretro.so", "zeebx_libretro.so")


def find_profile():
    """RetroArch's configuration folder, in the place where it looks for it."""
    import os

    if xdg := os.environ.get("XDG_CONFIG_HOME"):
        return pathlib.Path(xdg) / "retroarch"
    return pathlib.Path.home() / ".config" / "retroarch"


def find_so(release):
    profiles = ["release", "debug"] if release else ["debug", "release"]
    for profile in profiles:
        for name in NAMES:
            path = ROOT / "target" / profile / name
            if path.is_file():
                return path
    return None


# --- muOS -------------------------------------------------------------------------------------
#
# The muOS card does not use RetroArch's cores folder: the launcher calls
# `retroarch -L /opt/muos/share/core/<core>`, and what picks the core is the association file in
# `share/info/assign/<System>/<core>.ini`. The core's `.info` goes in
# `share/emulator/retroarch/info/`. Measured on the RG40XX-H image; the procedure is in
# `docs/libretro/HANDHELDS-ARM64.md`, and the two permission traps are there too.

SYSTEM = "Zeebo"
KEY = "zeebo"
SOUNDFONT_RELATIVE = pathlib.Path("emulator/retroarch/system/zeebx/aparelho/soundfonts")
FONT_RELATIVE = pathlib.Path("emulator/retroarch/system/zeebx/aparelho/shared/fonts/tectoy.ttf")


def install_on_muos(root, source_so, source_info, soundfont, font, roms_root, roms):
    """Installs the core, the `.info`, the associations and, if asked, the sample bank."""
    share = root / "opt/muos/share"
    if not (share / "core").is_dir():
        print(
            f"does not look like a mounted muOS card: {share / 'core'} is missing\n"
            "  mount the ROOTFS partition (the system one, not the ROMs one) and point to it",
            file=sys.stderr,
        )
        return 1

    # Backup with the date in the name: the previous core is the only way to go back without
    # rebuilding.
    import datetime

    keep = root / f"opt/muos/share/core/backup-{datetime.datetime.now():%Y%m%d-%H%M%S}"
    target_so = share / "core/zeebx_libretro.so"
    if target_so.is_file():
        keep.mkdir(parents=True, exist_ok=True)
        shutil.copy2(target_so, keep / target_so.name)
        print(f"backup: {keep / target_so.name}")

    shutil.copy(source_so, target_so)
    target_so.chmod(0o755)
    info = share / "emulator/retroarch/info/zeebx_libretro.info"
    info.parent.mkdir(parents=True, exist_ok=True)
    shutil.copy(source_info, info)
    print(f"core:  {target_so} ({target_so.stat().st_size} bytes)")
    print(f"info:  {info}")

    # The associations. `global.ini` gives the name and the default core; `[friendly]` is the key
    # that ties the ROMs folder to the system, and it is what `assign.sh` reads to generate
    # `assign.json`.
    assign = share / f"info/assign/{SYSTEM}"
    assign.mkdir(parents=True, exist_ok=True)
    (assign / "global.ini").write_text(
        f"[global]\nname={SYSTEM}\ndefault=zeebx\ncatalogue=Mobile - {SYSTEM}\n"
        "lookup=0\ngovernor=performance\n\n[friendly]\n"
        f"{KEY}\n",
        encoding="utf-8",
    )
    (assign / "zeebx.ini").write_text(
        "[zeebx]\nname=Zeebx\ncore=zeebx_libretro.so\n\n[launch]\nprep=\n"
        "exec=/opt/muos/script/launch/lr-general.sh\ndone=\n",
        encoding="utf-8",
    )
    print(f"assign: {assign}")

    # `assign.json` is generated by `assign.sh`, which does **not** run on every boot. Adding the
    # key here is doing what it would do, and it is what makes the system show up without a manual
    # task.
    assoc = share / "info/assign/assign.json"
    if assoc.is_file():
        import json

        data = json.loads(assoc.read_text(encoding="utf-8"))
        if data.get(KEY) != SYSTEM:
            data[KEY] = SYSTEM
            assoc.write_text(
                json.dumps(data, indent=2, ensure_ascii=False, sort_keys=True) + "\n",
                encoding="utf-8",
            )
            print(f"assign.json: + \"{KEY}\": \"{SYSTEM}\" ({len(data)} entries)")
    else:
        print(f"warning: {assoc} does not exist; run the *Refresh Automatic Core Assign* task on muOS")

    # The folder's display name. It lives in the store (`MUOS/info/name`), which is where the rest
    # of the names live.
    name_candidates = [root / "ROMS/MUOS/info/name/folder.json", root / "MUOS/info/name/folder.json"]
    if roms_root is not None:
        name_candidates.insert(0, roms_root / "MUOS/info/name/folder.json")
    for name in name_candidates:
        if not name.is_file():
            continue
        import json

        data = json.loads(name.read_text(encoding="utf-8"))
        if data.get(KEY) != SYSTEM:
            data[KEY] = SYSTEM
            name.write_text(
                json.dumps(data, indent=2, ensure_ascii=False, sort_keys=True) + "\n",
                encoding="utf-8",
            )
            print(f"{name.name}: + \"{KEY}\": \"{SYSTEM}\"")
        break

    if roms:
        if roms_root is None:
            print("--rom requires --roms with the root of the ROMs partition", file=sys.stderr)
            return 1
        target_roms = roms_root / "ROMS/Zeebo"
        target_roms.mkdir(parents=True, exist_ok=True)
        for rom in roms:
            if not rom.is_file():
                print(f"the ROM {rom} does not exist", file=sys.stderr)
                return 1
            shutil.copy2(rom, target_roms / rom.name)
            print(f"ROM:   {target_roms / rom.name}")

    if soundfont is not None:
        if not soundfont.is_file():
            print(f"the bank {soundfont} does not exist", file=sys.stderr)
            return 1
        target_soundfont = share / SOUNDFONT_RELATIVE
        target_soundfont.mkdir(parents=True, exist_ok=True)
        shutil.copy(soundfont, target_soundfont / soundfont.name)
        print(f"bank:  {target_soundfont / soundfont.name} ({soundfont.stat().st_size} bytes)")
        print("       the core itself states this path in the log when it does not find the bank")

    if font is not None:
        if not font.is_file():
            print(f"the font {font} does not exist", file=sys.stderr)
            return 1
        target_font = share / FONT_RELATIVE
        target_font.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(font, target_font)
        print(f"font:  {target_font} ({font.stat().st_size} bytes)")

    # Final check: copying without checking is copying without knowing.
    import hashlib

    def digest(path):
        return hashlib.sha256(path.read_bytes()).hexdigest()

    if digest(source_so) != digest(target_so):
        print("the sha256 of the copied core does not match", file=sys.stderr)
        return 1
    print(f"sha256 matches: {digest(target_so)[:16]}...")
    print("\nunmount the card before removing it (`udisksctl unmount -b /dev/sdX`)")
    return 0


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--dest", "--destino", type=pathlib.Path, default=None)
    ap.add_argument("--release", action="store_true", help="prefers target/release")
    ap.add_argument("--muos", type=pathlib.Path, default=None, help="root of the mounted muOS card")
    ap.add_argument("--soundfont", "--banco", type=pathlib.Path, default=None, help="the MIDI .sf2, with --muos")
    ap.add_argument("--so", type=pathlib.Path, help="the package's .so; no local build needed")
    ap.add_argument("--info", type=pathlib.Path, help="the package's .info; the repo's file is not needed")
    ap.add_argument("--font", type=pathlib.Path, help="tectoy.ttf, with --muos")
    ap.add_argument("--roms", type=pathlib.Path, help="mounted root of the muOS ROMs partition")
    ap.add_argument("--rom", type=pathlib.Path, action="append", default=[], help="ROM for ROMS/Zeebo; can repeat")
    args = ap.parse_args()

    source_so = args.so or find_so(args.release)
    source_info = args.info or SOURCE_INFO
    if source_so is None or not pathlib.Path(source_so).is_file():
        print("did not find the built core; use --so zeebx_libretro.so or do a local build", file=sys.stderr)
        return 1
    if not pathlib.Path(source_info).is_file():
        print(f"did not find {source_info}", file=sys.stderr)
        return 1

    if args.muos is not None:
        return install_on_muos(args.muos, pathlib.Path(source_so), pathlib.Path(source_info), args.soundfont, args.font, args.roms, args.rom)

    dest = args.dest or (find_profile() / "cores")
    dest.mkdir(parents=True, exist_ok=True)
    target_so = dest / "zeebx_libretro.so"
    target_info = dest / "zeebx_libretro.info"

    # Warns when the `.info` that is there differs from the one going in: it is the case that broke
    # the scan once, and a warning on the console costs less than finding out from the symptom.
    if target_info.is_file() and target_info.read_bytes() != pathlib.Path(source_info).read_bytes():
        print(f"warning: the .info in {target_info} was different and will be replaced")

    shutil.copy(source_so, target_so)
    shutil.copy(source_info, target_info)
    print(f"core:  {target_so}  ({source_so.stat().st_size} bytes, {source_so.parent.name})")
    print(f"info:  {target_info}")
    print("\nopen RetroArch and pick the Zeebx core; the No-Intro database comes from the `database` field here")
    return 0


if __name__ == "__main__":
    sys.exit(main())
