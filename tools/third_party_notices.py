#!/usr/bin/env python3
"""Generates `THIRD-PARTY-NOTICES.txt`: the licenses of everything Zeebx's binaries carry inside.

MIT, BSD, Apache, Zlib, OFL and Qt's LGPL ask for the copyright notice and the license text to go
along with the binary. The file is versioned and goes into every release package;
`release.yml` runs this script with `--check` and stops if it is stale.

Four parts, because `cargo about` only sees crates:

- the crates, through `cargo about` with the `about.toml` at the root;
- the C++ that `dynarmic` builds along (fmt, mcl, xbyak, zydis…), read from the crate's copy in
  cargo's registry;
- the Lucide icon font, embedded in the Qt frontend (see `tools/icons.py`);
- Qt 6, which goes inside the AppImage, the Windows installer and the Qt frontend's `.dmg`.

    python3 tools/third_party_notices.py          # rewrites the file
    python3 tools/third_party_notices.py --check  # only says whether it is up to date

The Portuguese option name (`--confere`) is still accepted.

Needs `cargo about` at the version below (`cargo install --locked cargo-about --features cli
--version ...`): another version formats differently, and `--check` would report a difference
that is not one.
"""

import json
import pathlib
import subprocess
import sys

CARGO_ABOUT_VERSION = "0.9.2"

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "THIRD-PARTY-NOTICES.txt"
LICENSES = ROOT / "tools" / "licenses"

# The dynarmic `externals` that go into the binary. Left out are `catch`, which is only for its
# tests, and `biscuit`, which is only built when the host is RISC-V.
DYNARMIC_EXTERNALS = [
    ("fmt", "externals/fmt/LICENSE"),
    ("mcl", "externals/mcl/LICENSE"),
    ("oaknut", "externals/oaknut/LICENSE"),
    ("robin-map", "externals/robin-map/LICENSE"),
    ("xbyak", "externals/xbyak/COPYRIGHT"),
    ("zydis", "externals/zydis/LICENSE"),
    ("zycore", "externals/zydis/dependencies/zycore/LICENSE"),
    ("Boost (headers)", "externals/ext-boost/LICENSE_1_0.txt"),
]

HEADER = """\
Third-party software in Zeebx
=============================

The Zeebx source code is GPL-2.0-or-later (see LICENSE). The binaries are distributed under the
GPLv3 (see LICENSE-GPL3), because they link Apache-2.0 libraries listed below.

This file lists the licenses of the third-party software included in those binaries. It is
generated by tools/third_party_notices.py; do not edit it by hand.
"""

QT = """\
================================================================================
Qt 6 (LGPL-3.0-only)

Used by: the Qt frontend (zeebx-qt). The AppImage, the Windows installer and the macOS .dmg ship
the Qt libraries QtCore, QtGui, QtQml and QtQuick, dynamically linked; the .deb uses the Qt from
the system. You may replace them with your own build of Qt.

Qt is Copyright (C) The Qt Company Ltd. and other contributors.
Source code: https://download.qt.io/official_releases/qt/
The LGPLv3 builds on the GPLv3, whose text is in LICENSE-GPL3.
--------------------------------------------------------------------------------

"""


def run(*command: str) -> str:
    return subprocess.run(command, cwd=ROOT, check=True, capture_output=True, text=True).stdout


def check_version() -> None:
    version = run("cargo", "about", "--version").split()[-1]
    if version != CARGO_ABOUT_VERSION:
        sys.exit(f"cargo about {version}, and the file is generated with {CARGO_ABOUT_VERSION}")


def crates() -> str:
    return run(
        "cargo", "about", "generate", "--workspace", "--all-features", "--locked",
        "-c", "about.toml", str(LICENSES / "about.hbs"),
    )


def dynarmic() -> str:
    metadata = json.loads(run("cargo", "metadata", "--format-version", "1", "--locked"))
    package = next(p for p in metadata["packages"] if p["name"] == "dynarmic")
    root = pathlib.Path(package["manifest_path"]).parent / "dynarmic"
    parts = []
    for name, path in [("dynarmic", "LICENSE.txt")] + DYNARMIC_EXTERNALS:
        text = (root / path).read_text(encoding="utf-8").strip()
        parts.append(
            "=" * 80 + f"\n{name} (C++, built into the dynarmic crate)\n" + "-" * 80
            + f"\n\n{text}\n\n"
        )
    return "".join(parts)


def lucide() -> str:
    text = (LICENSES / "lucide-LICENSE").read_text(encoding="utf-8").strip()
    return (
        "=" * 80
        + "\nLucide icons (ISC; MIT for the icons derived from Feather)\n\n"
        + "Used by: the Qt frontend (zeebx-qt), as a font with the icons of the toolbar and the\n"
        + "menus, embedded in the binary.\n"
        + "-" * 80
        + f"\n\n{text}\n\n"
    )


def generate() -> str:
    lgpl = (LICENSES / "LGPL-3.0.txt").read_text(encoding="utf-8")
    return HEADER + crates() + dynarmic() + lucide() + QT + lgpl


def main() -> None:
    check_version()
    text = generate()
    if {"--check", "--confere"} & set(sys.argv[1:]):
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            sys.exit(
                "THIRD-PARTY-NOTICES.txt is stale: run python3 tools/third_party_notices.py"
            )
        print("THIRD-PARTY-NOTICES.txt up to date")
        return
    OUT.write_text(text, encoding="utf-8")
    print(f"{OUT.name}: {len(text) // 1024} KiB")


if __name__ == "__main__":
    main()
